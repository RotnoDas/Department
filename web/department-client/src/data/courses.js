/**
 * Returns all courses for a given semester number (1-8).
 * Accepts number or string representation (e.g. 6 or "6" or "6th Semester").
 */
export function getCoursesBySemester(semesterInput) {
  let sem = semesterInput;
  if (typeof sem === "string") {
    const match = sem.match(/\d+/);
    sem = match ? parseInt(match[0], 10) : 1;
  }
  return SEMESTER_COURSES[sem] || SEMESTER_COURSES[1];
}

/**
 * Calculates total credits for a given semester.
 */
export function getSemesterTotalCredits(semesterInput) {
  const courses = getCoursesBySemester(semesterInput);
  return courses.reduce((sum, c) => sum + (Number(c.credits) || 0), 0);
}

/**
 * Returns flattened array of all courses across all 8 semesters, tagged with semester.
 */
export function getAllCurriculumCourses() {
  const all = [];
  for (const [semNum, list] of Object.entries(SEMESTER_COURSES)) {
    for (const c of list) {
      all.push({
        ...c,
        semesterNum: Number(semNum),
        semester: SEMESTER_LABELS[semNum],
      });
    }
  }
  return all;
}
